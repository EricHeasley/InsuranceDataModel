#!/usr/bin/env python3
"""Generate derived artifacts from the model.

  dist/insurance-data-model.json          resolved single-file model (mixins expanded)
  dist/insurance-data-model.schema.json   all entity schemas bundled into one file ($defs per entity)
  dist/postgres/schema.sql                PostgreSQL DDL
  docs/data-dictionary.md                 entity / attribute / enum reference
  docs/diagrams.md                        Mermaid ER diagrams per domain

Run with --check to fail if committed artifacts are out of date.
"""
import hashlib
import json
import sys

import idm

GENERATED = "Generated by tools/build.py from schemas/. Do not edit."


def resolved_model(model: dict) -> str:
    out = {k: model[k] for k in ("name", "title", "version", "description", "conventions", "types")}
    out["domains"] = [{"name": d["name"], "description": d["description"]} for d in model["domains"]]
    out["enums"] = model["enums"]
    out["entities"] = {}
    for name, e in model["entities"].items():
        ent = {"domain": e["domain"], "description": e["description"]}
        if e.get("subtypeOf"):
            ent["subtypeOf"] = e["subtypeOf"]
        ent["primaryKey"] = e["primaryKey"]
        if e.get("unique"):
            ent["unique"] = e["unique"]
        ent["attributes"] = [{k: v for k, v in a.items() if k != "mixin"} for a in e["attributes"]]
        out["entities"][name] = ent
    return json.dumps(out, indent=2) + "\n"


def json_schema(model: dict) -> str:
    defs = {}
    for name, e in model["entities"].items():
        props, required = {}, []
        for a in e["attributes"]:
            prop = dict(model["types"][a["type"]]["jsonSchema"])
            if a["type"] == "string":
                prop["maxLength"] = a.get("maxLength", 255)
            if "enum" in a:
                prop["enum"] = list(model["enums"][a["enum"]]["values"])
            if a.get("required"):
                required.append(a["name"])
            if a.get("description"):
                prop["description"] = a["description"]
            if a.get("references"):
                prop["x-references"] = a["references"]
            if a.get("sensitivity"):
                prop["x-sensitivity"] = a["sensitivity"]
            props[a["name"]] = prop
        defs[name] = {
            "type": "object",
            "description": e["description"],
            "x-domain": e["domain"],
            "x-primaryKey": e["primaryKey"],
            **({"x-unique": e["unique"]} if e.get("unique") else {}),
            **({"x-subtypeOf": e["subtypeOf"]} if e.get("subtypeOf") else {}),
            "properties": props,
            "required": required,
            "additionalProperties": False,
        }
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://github.com/EricHeasley/InsuranceDataModel/dist/insurance-data-model.schema.json",
        "title": model["title"],
        "description": f"{GENERATED} Version {model['version']}. Validate a record with {{\"$ref\": \"#/$defs/<entity>\"}}.",
        "$defs": defs,
    }
    return json.dumps(schema, indent=2) + "\n"


def _pg_type(model: dict, a: dict) -> str:
    if a["type"] == "string":
        return f"varchar({a.get('maxLength', 255)})"
    return model["types"][a["type"]]["postgres"]


def _ident(prefix: str, *parts: str) -> str:
    name = "_".join((prefix,) + parts)
    if len(name) > 63:
        name = name[:54] + "_" + hashlib.sha1(name.encode()).hexdigest()[:8]
    return name


def postgres(model: dict) -> str:
    tables, fks, indexes = [], [], []
    for name, e in model["entities"].items():
        cols = []
        for a in e["attributes"]:
            line = f"  {a['name']} {_pg_type(model, a)}"
            if a.get("required"):
                line += " NOT NULL"
            if "enum" in a:
                values = ", ".join(f"'{v}'" for v in model["enums"][a["enum"]]["values"])
                line += f" CONSTRAINT {_ident('ck', name, a['name'])} CHECK ({a['name']} IN ({values}))"
            cols.append(line)
            if a.get("references"):
                tgt, _, tcol = a["references"].partition(".")
                fks.append(f"ALTER TABLE {name} ADD CONSTRAINT {_ident('fk', name, a['name'])} "
                           f"FOREIGN KEY ({a['name']}) REFERENCES {tgt} ({tcol});")
                if [a["name"]] != e["primaryKey"]:
                    indexes.append(f"CREATE INDEX {_ident('ix', name, a['name'])} ON {name} ({a['name']});")
        cols.append(f"  CONSTRAINT {_ident('pk', name)} PRIMARY KEY ({', '.join(e['primaryKey'])})")
        for key in e.get("unique", []):
            cols.append(f"  CONSTRAINT {_ident('uq', name, *key)} UNIQUE ({', '.join(key)})")
        desc = e["description"].replace("'", "''")
        tables.append(f"CREATE TABLE {name} (\n" + ",\n".join(cols) + f"\n);\nCOMMENT ON TABLE {name} IS '{desc}';")
    return "\n\n".join([f"-- {GENERATED}\n-- {model['title']} {model['version']}", *tables,
                        "-- Foreign keys", "\n".join(fks), "-- Foreign key indexes", "\n".join(indexes)]) + "\n"


def _cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def data_dictionary(model: dict) -> str:
    out = [f"# Data dictionary", "", f"<!-- {GENERATED} -->", "",
           f"{model['title']} version {model['version']}: {len(model['entities'])} entities, {len(model['enums'])} code lists.", "",
           "Sens. = data sensitivity tag (PII, PHI, PCI, SPI). Attributes in *italics* come from a mixin.", "", "## Contents", ""]
    for d in model["domains"]:
        names = [n for n, e in model["entities"].items() if e["domain"] == d["name"]]
        out.append(f"- [{d['name']}](#{d['name']}): " + ", ".join(f"[{n}](#{n})" for n in names))
    out.append("- [Code lists](#code-lists)")
    for d in model["domains"]:
        out += ["", f"## {d['name']}", "", d["description"]]
        for name, e in model["entities"].items():
            if e["domain"] != d["name"]:
                continue
            out += ["", f"### {name}", "", e["description"], "", f"Schema: [`schemas/{d['name']}/{name}.schema.json`](../schemas/{d['name']}/{name}.schema.json)", ""]
            if e.get("subtypeOf"):
                out += [f"Subtype of [{e['subtypeOf']}](#{e['subtypeOf']}).", ""]
            if e.get("unique"):
                out += ["Unique: " + "; ".join("(" + ", ".join(k) + ")" for k in e["unique"]) + ".", ""]
            out += ["| Attribute | Type | Req. | References / code list | Sens. | Description |", "|---|---|---|---|---|---|"]
            for a in e["attributes"]:
                label = f"`{a['name']}`"
                if a["name"] in e["primaryKey"]:
                    label += " 🔑"
                if a["mixin"]:
                    label = f"*{label}*"
                typ = a["type"] + (f"({a['maxLength']})" if "maxLength" in a else "")
                link = ""
                if a.get("references"):
                    tgt = a["references"].split(".")[0]
                    link = f"→ [{tgt}](#{tgt})"
                elif a.get("enum"):
                    link = f"[{a['enum']}](#code-list-{a['enum']})"
                out.append(f"| {label} | {typ} | {'yes' if a.get('required') else ''} | {link} | "
                           f"{a.get('sensitivity', '')} | {_cell(a.get('description', ''))} |")
    out += ["", "## Code lists", ""]
    for name in sorted(model["enums"]):
        enum = model["enums"][name]
        out += [f'<a id="code-list-{name}"></a>', "", f"**{name}** ({enum['domain']}): {enum['description']}", ""]
        out += [f"- `{code}`" + (f": {desc}" if desc else "") for code, desc in enum["values"].items()]
        out.append("")
    return "\n".join(out)


def diagrams(model: dict) -> str:
    ents = model["entities"]
    out = ["# Diagrams", "", f"<!-- {GENERATED} -->", "", "## Domain dependencies", "",
           "An arrow from A to B means entities in A reference entities in B; the label is the number of references.", "",
           "```mermaid", "flowchart LR"]
    counts = {}
    for e in ents.values():
        for a in e["attributes"]:
            if a.get("references"):
                pair = (e["domain"], ents[a["references"].split(".")[0]]["domain"])
                if pair[0] != pair[1]:
                    counts[pair] = counts.get(pair, 0) + 1
    out += [f"  {a} -->|{n}| {b}" for (a, b), n in sorted(counts.items())]
    out.append("```")
    for d in model["domains"]:
        out += ["", f"## {d['name']}", "", "Relationships within the domain; only key attributes are shown. "
                "References to other domains are listed in the [data dictionary](data-dictionary.md).", "", "```mermaid", "erDiagram"]
        for name, e in ents.items():
            if e["domain"] != d["name"]:
                continue
            out.append(f"  {name} {{")
            for a in e["attributes"]:
                is_pk, is_fk = a["name"] in e["primaryKey"], bool(a.get("references"))
                if (is_pk or is_fk) and not a["mixin"]:
                    keys = ",".join(k for k, on in (("PK", is_pk), ("FK", is_fk)) if on)
                    out.append(f"    {a['type']} {a['name']} {keys}")
            out.append("  }")
        for name, e in ents.items():
            if e["domain"] != d["name"]:
                continue
            for a in e["attributes"]:
                if not a.get("references") or a["mixin"]:
                    continue
                tgt = a["references"].split(".")[0]
                if ents[tgt]["domain"] != d["name"]:
                    continue
                if [a["name"]] == e["primaryKey"]:
                    out.append(f'  {tgt} ||--o| {name} : "is a"')
                else:
                    card = "||" if a.get("required") else "o|"
                    out.append(f'  {tgt} {card}--o{{ {name} : "{a["name"]}"')
        out.append("```")
    return "\n".join(out) + "\n"


def main() -> int:
    model = idm.load()
    errors = idm.validate(model)
    if errors:
        print("\n".join(f"ERROR {e}" for e in errors))
        return 1
    outputs = {
        "dist/insurance-data-model.json": resolved_model(model),
        "dist/insurance-data-model.schema.json": json_schema(model),
        "dist/postgres/schema.sql": postgres(model),
        "docs/data-dictionary.md": data_dictionary(model),
        "docs/diagrams.md": diagrams(model),
    }
    check, stale = "--check" in sys.argv, []
    for rel, content in outputs.items():
        path = idm.ROOT / rel
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {rel}")
    if stale:
        print("out of date (run tools/build.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
